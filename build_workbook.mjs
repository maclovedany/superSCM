function title(sheet, text, lastCol) {
  const r = sheet.getRange(`A1:${lastCol}1`);
  r.merge();
  r.values = [[text]];
  r.format = { fill: colors.navy, font: { bold: true, color: colors.white, size: 16 }, horizontalAlignment: 'center', verticalAlignment: 'center' };
  r.format.rowHeight = 30;
}
function subtitle(sheet, text, lastCol) {
  const r = sheet.getRange(`A2:${lastCol}2`);
  r.merge();
  r.values = [[text]];
  r.format = { fill: colors.lightBlue, font: { italic: true, color: colors.dark, size: 10 }, wrapText: true, verticalAlignment: 'center' };
  r.format.rowHeight = 32;
}
function header(sheet, range) {
  const r = sheet.getRange(range);
  r.format = { fill: colors.blue, font: { bold: true, color: colors.dark }, horizontalAlignment: 'center', verticalAlignment: 'center', wrapText: true, borders: { preset: 'all', style: 'thin', color: colors.border } };
  r.format.rowHeight = 28;
}
function body(sheet, range) {
  const r = sheet.getRange(range);
  r.format = { verticalAlignment: 'center', wrapText: true, borders: { insideHorizontal: { style: 'thin', color: colors.border }, insideVertical: { style: 'thin', color: colors.border }, bottom: { style: 'thin', color: colors.border } } };
}
function section(sheet, range, text) {
  const r = sheet.getRange(range);
  r.merge(); r.values = [[text]];
  r.format = { fill: colors.teal, font: { bold: true, color: colors.navy }, verticalAlignment: 'center' };
  r.format.rowHeight = 22;
}
function widths(sheet, map) {
  for (const [col, w] of Object.entries(map)) sheet.getRange(`${col}:${col}`).format.columnWidth = w;
}

