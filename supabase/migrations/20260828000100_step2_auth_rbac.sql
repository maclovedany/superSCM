do $public_rbac$
declare
  table_name text;
begin
  foreach table_name in array array[
    'planning_runs', 'ol_demand', 'sfdc_pipeline', 'bulk_deals',
    'historical_actuals', 'demand_confirmations'
  ] loop
    if to_regclass(format('public.%I', table_name)) is not null then
      execute format('alter table public.%I enable row level security', table_name);
      execute format('revoke all on public.%I from anon', table_name);
      execute format('grant select, insert, update, delete on public.%I to authenticated', table_name);
      execute format('drop policy if exists %I on public.%I', table_name || '_user_select', table_name);
      execute format('drop policy if exists %I on public.%I', table_name || '_admin_mutation', table_name);
      execute format('create policy %I on public.%I for select to authenticated using (core.is_active_user())', table_name || '_user_select', table_name);
      execute format('create policy %I on public.%I for all to authenticated using (core.is_admin()) with check (core.is_admin())', table_name || '_admin_mutation', table_name);
    end if;
  end loop;
end;
$public_rbac$;

