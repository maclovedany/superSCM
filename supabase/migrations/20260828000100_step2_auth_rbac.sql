create schema if not exists core;
create schema if not exists analytics;

create table if not exists core.app_user (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null default '',
  department text,
  role text not null default 'USER' check (role in ('ADMIN', 'USER')),
  active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists core.audit_log (
  id bigint generated by default as identity primary key,
  actor uuid references auth.users(id) on delete set null,
  action text not null,
  target_type text not null,
  target_id text not null,
  before jsonb,
  after jsonb,
  at timestamptz not null default now()
);

create index if not exists app_user_role_active_idx on core.app_user (role, active);
create index if not exists audit_log_target_idx on core.audit_log (target_type, target_id, at desc);
create index if not exists audit_log_actor_idx on core.audit_log (actor, at desc);

create or replace function core.set_updated_at()
returns trigger
language plpgsql
set search_path = core, pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function core.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = core, auth, pg_temp
as $$
begin
  insert into core.app_user (user_id, email, name, department, role, active)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'name', new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, ''), '@', 1)),
    nullif(new.raw_user_meta_data ->> 'department', ''),
    'USER',
    true
  )
  on conflict (user_id) do update
    set email = excluded.email,
        name = case when core.app_user.name = '' then excluded.name else core.app_user.name end,
        updated_at = now();
  return new;
end;
$$;

create or replace function core.is_admin(check_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = core, pg_temp
as $$
  select exists (
    select 1
      from core.app_user
     where user_id = check_user_id
       and role = 'ADMIN'
       and active = true
  );
$$;

create or replace function core.is_active_user(check_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = core, pg_temp
as $$
  select exists (
    select 1
      from core.app_user
     where user_id = check_user_id
       and active = true
  );
$$;

create or replace function core.mark_login()
returns void
language sql
volatile
security definer
set search_path = core, pg_temp
as $$
  update core.app_user
     set last_login_at = now(), updated_at = now()
   where user_id = auth.uid()
     and active = true;
$$;

create or replace function core.protect_self_admin_change()
returns trigger
language plpgsql
set search_path = core, pg_temp
as $$
begin
  if auth.uid() = old.user_id and old.role = 'ADMIN' and new.role <> 'ADMIN' then
    raise exception '자신의 관리자 권한은 제거할 수 없습니다.' using errcode = '42501';
  end if;
  if auth.uid() = old.user_id and old.active = true and new.active = false then
    raise exception '자신의 계정은 비활성화할 수 없습니다.' using errcode = '42501';
  end if;
  return new;
end;
$$;

create or replace function core.audit_app_user_change()
returns trigger
language plpgsql
security definer
set search_path = core, pg_temp
as $$
begin
  if old.role is distinct from new.role then
    insert into core.audit_log (actor, action, target_type, target_id, before, after)
    values (
      auth.uid(), 'USER_ROLE_CHANGED', 'app_user', new.user_id::text,
      jsonb_build_object('role', old.role, 'active', old.active),
      jsonb_build_object('role', new.role, 'active', new.active)
    );
  end if;

  if old.active is distinct from new.active then
    insert into core.audit_log (actor, action, target_type, target_id, before, after)
    values (
      auth.uid(), 'USER_ACTIVE_CHANGED', 'app_user', new.user_id::text,
      jsonb_build_object('role', old.role, 'active', old.active),
      jsonb_build_object('role', new.role, 'active', new.active)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update of email, raw_user_meta_data on auth.users
  for each row execute function core.handle_new_auth_user();

drop trigger if exists app_user_set_updated_at on core.app_user;
create trigger app_user_set_updated_at
  before update on core.app_user
  for each row execute function core.set_updated_at();

drop trigger if exists app_user_protect_self_change on core.app_user;
create trigger app_user_protect_self_change
  before update of role, active on core.app_user
  for each row execute function core.protect_self_admin_change();

drop trigger if exists app_user_audit_change on core.app_user;
create trigger app_user_audit_change
  after update of role, active on core.app_user
  for each row execute function core.audit_app_user_change();

insert into core.app_user (user_id, email, name, department, role, active, created_at, updated_at)
select id,
       coalesce(email, ''),
       coalesce(raw_user_meta_data ->> 'name', raw_user_meta_data ->> 'full_name', split_part(coalesce(email, ''), '@', 1)),
       nullif(raw_user_meta_data ->> 'department', ''),
       'USER',
       true,
       created_at,
       now()
  from auth.users
on conflict (user_id) do nothing;

