drop policy if exists app_user_select_self_or_admin on core.app_user;
create policy app_user_select_self_or_admin
  on core.app_user
  for select
  to authenticated
  using (user_id = auth.uid() or core.is_admin());

drop policy if exists app_user_admin_update on core.app_user;
create policy app_user_admin_update
  on core.app_user
  for update
  to authenticated
  using (core.is_admin())
  with check (core.is_admin());

drop policy if exists audit_log_admin_select on core.audit_log;
create policy audit_log_admin_select
  on core.audit_log
  for select
  to authenticated
  using (core.is_admin());

