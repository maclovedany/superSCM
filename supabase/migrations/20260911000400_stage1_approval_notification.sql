          'message', '만료된 임시배정과 연결된 주문 상태를 확인해 주세요.'
        )
      );
      v_count := v_count + 1;
    end loop;
  end loop;
  return v_count;
end;
$$;


-- ══ 10. 사용자·관리자 조회 뷰와 읽음 처리 ════════════════════

create or replace view analytics.v_my_notification
with (security_invoker = true)
as
select
  o.notification_id, o.template_code,
  coalesce(nullif(o.payload ->> 'title', ''), '알림') as title,
  coalesce(o.payload ->> 'message', '') as message,
  o.payload, n.created_at, n.read_at
from core.user_notification n
join core.notification_outbox o on o.notification_id = n.notification_id
where n.recipient_user_id = auth.uid();

create or replace view analytics.v_notification_delivery
with (security_invoker = true)
as
select
  d.delivery_id, d.notification_id, o.template_code,
  d.recipient_user_id, d.recipient_email,
  coalesce(nullif(u.name, ''), u.email, d.recipient_user_id::text) as recipient_name,
  d.channel, d.status, d.attempted_at, d.error_message, d.external_message_id,
  d.attempt_number, d.retryable
from core.notification_delivery d
join core.notification_outbox o on o.notification_id = d.notification_id
left join core.app_user u on u.user_id = d.recipient_user_id
where core.is_admin();

create or replace function core.mark_notification_read(p_notification_id uuid)
returns void
language plpgsql
security definer
set search_path = core, public, pg_temp
as $$
begin
  if auth.uid() is null then
    raise exception '로그인이 필요합니다.' using errcode = '42501';
  end if;
  update core.user_notification
     set read_at = coalesce(read_at, clock_timestamp())
   where notification_id = p_notification_id
     and recipient_user_id = auth.uid();
  if not found then
    raise exception '읽을 알림을 찾을 수 없습니다.' using errcode = 'P0002';
  end if;
end;
$$;


