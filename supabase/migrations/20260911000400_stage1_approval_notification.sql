create table if not exists core.approval_event (
  event_id          bigint generated by default as identity primary key,
  approval_id       uuid not null references core.approval_request(approval_id) on delete restrict,
  event_type        text not null check (event_type in ('REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
  previous_status   text check (previous_status is null or previous_status in ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
  next_status       text not null check (next_status in ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
  actor             uuid not null references auth.users(id) on delete restrict,
  comment           text,
  payload_snapshot  jsonb not null,
  at                timestamptz not null default now(),
  constraint approval_event_transition_check check (
    (event_type = 'REQUESTED' and previous_status is null and next_status = 'PENDING')
    or (event_type in ('APPROVED', 'REJECTED', 'CANCELLED')
        and previous_status = 'PENDING' and next_status = event_type)
  )
);

