from core.approval_request
order by requested_at desc;

select action, target_type, target_id
from core.audit_log
where target_type = 'APPROVAL_REQUEST'
order by at desc;

select c.relname, c.reloptions
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'analytics'
  and c.relname in ('v_my_approval_inbox', 'v_approval_history')
order by c.relname;
-- 기대: 두 뷰 모두 reloptions에 security_invoker=true

select r.approval_id, r.status,
       count(distinct e.event_id) as event_count,
       count(distinct a.id) as audit_count
from core.approval_request r
left join core.approval_event e on e.approval_id = r.approval_id
left join core.audit_log a
  on a.target_type = 'APPROVAL_REQUEST'
 and a.target_id = r.approval_id::text
group by r.approval_id, r.status
order by max(r.requested_at) desc;
