  );

drop policy if exists approval_event_read_related on core.approval_event;
create policy approval_event_read_related
  on core.approval_event
  for select
  to authenticated
  using (
    exists (
      select 1
        from core.approval_request r
       where r.approval_id = approval_event.approval_id
    )
  );

revoke all on core.approval_request, core.approval_event from anon, public;
