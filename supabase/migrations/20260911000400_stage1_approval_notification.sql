-- ══ 1. 승인 요청 원장과 append-only 이벤트 ═══════════════════

create table if not exists core.approval_request (
  approval_id       uuid primary key default gen_random_uuid(),
  approval_type     text not null check (approval_type in (
    'ITEM_POLICY', 'ALLOC_PRIORITY', 'EVENT_ORDER', 'PURCHASE_PLAN'
  )),
  target_type       text not null check (btrim(target_type) <> ''),
  target_id         text not null check (btrim(target_id) <> ''),
  payload           jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  status            text not null default 'PENDING' check (status in (
    'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'
  )),
  reason_code       text,
  reason_text       text,
  requested_by      uuid not null references auth.users(id) on delete restrict,
  requester_name    text not null check (btrim(requester_name) <> ''),
  requested_at      timestamptz not null default now(),
  decided_by        uuid references auth.users(id) on delete restrict,
  decider_name      text,
  decided_at        timestamptz,
  decision_comment  text,
  constraint approval_request_decision_check check (
    (status = 'PENDING' and decided_by is null and decider_name is null
        and decided_at is null and decision_comment is null)
    or (status = 'APPROVED' and decided_by is not null
        and nullif(btrim(decider_name), '') is not null and decided_at is not null)
    or (status = 'REJECTED' and decided_by is not null and decided_at is not null
        and nullif(btrim(decider_name), '') is not null
        and nullif(btrim(decision_comment), '') is not null)
    or (status = 'CANCELLED' and decided_by is not null
        and nullif(btrim(decider_name), '') is not null and decided_at is not null)
  )
);

