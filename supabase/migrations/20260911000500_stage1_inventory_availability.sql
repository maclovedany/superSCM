--   이미 원장에 있는 입고 중 그 스냅샷 시각 이후인 것이 그때 자동으로 반영된다 — 입고가
--   스냅샷보다 먼저 들어와도 값이 사라지지 않는다.
create or replace function core.apply_stock_receipts_from_batch(p_batch_id uuid)
returns integer
language plpgsql
security definer
set search_path = core, public, pg_temp
as $$
declare
  v_count integer;
  v_item_ids text[];
begin
  with completed as (
    -- "창고 입고 완료일과 완료 상태가 모두 확인된 건" = 입고일이 있고 receipt_status가
    -- COMPLETED인 건. 그 밖(미완료·상태 미상)은 여기서 제외되며 0으로도 세지 않는다.
    -- ★ fix round 3: 수량이 0(또는 그 이하)인 완료 입고도 여기서 제외한다.
    --   lib/import/validate.ts는 음수만 막고 0은 통과시키므로, 0 수량 COMPLETED 행이 그대로
    --   core.stock_receipt_ledger에 들어가면 그 표의 qty > 0 체크에 걸려 예외가 나고
    --   commit_import_batch 트랜잭션 전체가 롤백된다(그 배치의 다른 정상 입고까지 함께
    --   사라진다). 수량 0인 입고는 잔액을 바꾸지 않으므로 원장에 남기지 않아도 정확하다.
    select
      upper(regexp_replace(g."품목코드", '[\s\-_]', '', 'g')) as item_id,
      nullif(g."입고수량", '')::numeric as qty,
      nullif(g."입고일", '')::timestamptz as completed_at,
      g.source_record_id
    from raw.goods_receipt g
    where g.batch_id = p_batch_id
      and g.receipt_status = 'COMPLETED'
      and nullif(g."입고일", '') is not null
      and nullif(g."입고수량", '') is not null
      and nullif(g."입고수량", '')::numeric > 0
      and g.source_record_id is not null
  ),
  inserted as (
    -- ★ fix round 3: (source_record_id, item_id) 조합으로 conflict를 판정한다. 같은
    --   입고번호에 품목이 여러 줄이면 품목마다 각각 반영된다(위 표 코멘트 참고).
    insert into core.stock_receipt_ledger (item_id, source_record_id, qty, completed_at, source_batch_id)
    select item_id, source_record_id, qty, completed_at, p_batch_id
      from completed
    on conflict (source_record_id, item_id) do nothing
    returning item_id
  )
  select array_agg(distinct item_id) into v_item_ids from inserted;

  v_count := coalesce(array_length(v_item_ids, 1), 0);

  -- core.stock_balance에 아직 행이 없는 품목은 이 호출이 그냥 건너뛴다(update 대상 0행).
  if v_item_ids is not null then
    perform core.recompute_stock_balance_totals(v_item_ids);
  end if;

  return v_count;
end;
$$;

