-- 완료된 입고를 반영한 append-only 원장. 같은 입고 건(source_record_id, item_id 조합)은
-- 한 번만 반영된다(유니크 제약 + on conflict do nothing) — 배치를 다시 커밋하거나 재반영을
-- 여러 번 호출해도 이중 계산되지 않는다. 행을 지우거나 고치지 않는다 — 반영 시점의 사실을
-- 그대로 남긴다.
--
-- ★ fix round 3: 유니크 키를 source_record_id 단독에서 (source_record_id, item_id)로
--   바꿨다. 입고 한 건(입고번호)에 품목이 여러 줄로 딸린 ERP 문서가 흔한데, source_record_id
--   단독 유니크였다면 같은 입고번호의 두 번째 품목부터는 on conflict do nothing에 걸려
--   영원히 누락됐다. raw.goods_receipt 자체의 문제는 아래 core.commit_import_batch 확장
--   설명에 남겨 뒀다 — 이번 라운드에서 STEP 4의 raw 적재 키는 바꾸지 않는다.
create table if not exists core.stock_receipt_ledger (
