-- 창고코드·재고상태 → 범위 코드. 가장 구체적인 규칙이 이긴다:
--   3순위(가장 구체적) 창고+상태 모두 일치
--   2순위             창고전용 규칙(그 창고는 상태와 무관하게 이 범위)
--   1순위             상태전용 규칙(그 상태는 창고와 무관하게 이 범위)
-- 매칭되는 규칙이 없으면 null — 분류 불가이며 core.stock_balance 계산에서 그 행을 제외한다.
create or replace function core.classify_inventory_scope(p_warehouse_code text, p_raw_status text)
returns text
language sql
stable
set search_path = core, pg_temp
as $$
  select r.scope_code
    from core.inventory_scope_rule r
   where (r.warehouse_code = p_warehouse_code or r.warehouse_code is null)
     and (r.raw_status = p_raw_status or r.raw_status is null)
   order by
     (case when r.warehouse_code is not null and r.raw_status is not null then 3
           when r.warehouse_code is not null then 2
           when r.raw_status is not null then 1
           else 0 end) desc,
     r.rule_id
   limit 1;
$$;

