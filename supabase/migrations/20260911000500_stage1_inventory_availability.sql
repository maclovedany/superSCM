  '분류 불가 품목은 null + INVENTORY_SCOPE_UNCLASSIFIED';


-- ══ 4-1. 영업 전용 주문 가능 수량 뷰 ═══════════════════════════════
--
-- ★ ATP_VIEW만 가진 사용자(영업담당자)는 재고 상세를 보면 안 되고 실제 주문 가능 수량만
--   본다(stage1 §2, 계획서 Task 11 "정상재고에서 모든 배정·hold를 차감한 주문 가능 수량").
-- ★ 열은 최소로 고정한다 — item_id · item_name · available_qty · reason_code. Task 5가
--   같은 뷰를 create or replace로 확장할 것이므로 이름과 순서를 여기서 고정해 둔다
--   (기존 열 중간에 끼워 넣지 않는다, error.md #16).

create or replace view analytics.v_order_available_stock
with (security_invoker = true)
as
select
  im.item_id,
  im.item_name,
  case when sb.normal_qty is null then null
       else sb.normal_qty - 0::numeric - 0::numeric - 0::numeric
  end as available_qty,
  case when sb.item_id is null then 'INVENTORY_SCOPE_UNCLASSIFIED' end as reason_code
from core.v_item_master im
left join core.stock_balance sb on sb.item_id = im.item_id
where core.has_permission('ATP_VIEW');

comment on view analytics.v_order_available_stock is
  'Task 4 — 영업(ATP_VIEW) 전용 주문 가능 수량. 재고 상세(배정 내역 · Open PO · 이동 중 ·
