-- ══ 3. 확정 정상 창고재고 ═════════════════════════════════════════
--
-- ★ 이 배치가 담긴 품목만 갱신한다. 배치에 없는 기존 품목은 이전 확정값을 그대로 유지한다 —
--   즉 "품목별 최신값 누적"이며, 매번 raw.inventory 전체를 다시 계산하는 전체 스냅샷이
--   아니다(리뷰에서 지적된 deferred 항목 — 지금은 이 동작을 바꾸지 않고 사실만 적어 둔다).
--
-- ★ fix round 2: normal_qty를 두 부분으로 나눠서 관리한다.
--   snapshot_qty  최근 반영된 inventory 배치에서 NORMAL로 분류된 실사 수량 그 자체.
--   normal_qty    화면·뷰가 실제로 읽는 값. snapshot_qty + "그 스냅샷 시각 이후 완료된 입고
--                 합"이다 — raw.goods_receipt는 "창고 입고 완료일과 완료 상태가 모두
--                 확인된 건만 stock_balance 증가 원장으로 연결한다"(brief 원문)는 요구를
--                 이렇게 만족한다. 새 실사 스냅샷이 들어오면 그 시점 이전 입고는 이미 실사에
--                 잡혔다고 보고 더 이상 더하지 않는다(중복 계산 방지).

create table if not exists core.stock_balance (
  item_id         text primary key,
  snapshot_qty    numeric not null default 0 check (snapshot_qty >= 0),
  normal_qty      numeric not null default 0 check (normal_qty >= 0),
  snapshot_at     timestamptz,
  source_batch_id uuid references core.upload_batch(batch_id) on delete set null,
  updated_at      timestamptz not null default now()
);

