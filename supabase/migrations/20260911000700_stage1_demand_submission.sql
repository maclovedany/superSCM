alter table core.demand_submission_event enable row level security;

drop policy if exists planning_cycle_read on core.planning_cycle;
create policy planning_cycle_read on core.planning_cycle
  for select to authenticated using (true);

-- 검증 체크리스트: 다른 부서 제출본은 RLS로도 보이지 않는다. 본인 부서(DEMAND_SUBMIT) 또는
-- 취합 권한(DEMAND_CONSOLIDATE·PLAN_CONFIRM)·ADMIN만 조회할 수 있다(컨트롤러 판정 6).
drop policy if exists demand_submission_read_own_or_scm on core.demand_submission;
create policy demand_submission_read_own_or_scm on core.demand_submission
  for select to authenticated
  using (
    (
      core.has_permission('DEMAND_SUBMIT')
      and department = (select u.department from core.app_user u where u.user_id = auth.uid())
    )
    or core.has_permission('DEMAND_CONSOLIDATE')
    or core.has_permission('PLAN_CONFIRM')
    or core.is_admin()
  );

drop policy if exists demand_submission_line_read on core.demand_submission_line;
create policy demand_submission_line_read on core.demand_submission_line
  for select to authenticated
  using (exists (
    select 1 from core.demand_submission s where s.submission_id = demand_submission_line.submission_id
  ));

drop policy if exists demand_submission_event_read on core.demand_submission_event;
create policy demand_submission_event_read on core.demand_submission_event
  for select to authenticated
  using (exists (
    select 1 from core.demand_submission s where s.submission_id = demand_submission_event.submission_id
  ));

revoke all on core.planning_cycle, core.demand_submission, core.demand_submission_line, core.demand_submission_event
  from anon, public;
-- 모든 쓰기는 위 security definer 함수를 통해서만 한다 — 직접 INSERT/UPDATE/DELETE는 막는다
-- (검증 체크리스트: 서버와 RLS 모두에서 거절). 함수 안의 부서 비교가 최종 방어선이다.
