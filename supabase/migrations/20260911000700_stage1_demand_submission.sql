create or replace view analytics.v_demand_submission_status
with (security_invoker = true)
as
select
  s.submission_id, s.cycle_id, s.plan_month, s.department, s.status,
  c.submission_deadline,
  coalesce(l.total_line_count, 0) as total_line_count,
  coalesce(l.error_line_count, 0) as error_line_count,
  s.submitted_by, core.order_actor_name(s.submitted_by) as submitted_by_name, s.submitted_at,
  s.withdrawn_by, core.order_actor_name(s.withdrawn_by) as withdrawn_by_name, s.withdrawn_at, s.withdraw_reason,
  s.agreed_by, core.order_actor_name(s.agreed_by) as agreed_by_name, s.agreed_at,
  s.last_modified_by, core.order_actor_name(s.last_modified_by) as last_modified_by_name, s.last_modified_at,
  s.version, s.created_at,
  (
    s.status in ('DRAFT', 'WITHDRAWN')
    -- core.raise_demand_submission_reminders와 같은 이유로 date를 먼저 timestamp로 캐스팅한다
    -- (세션 timezone에 좌우되지 않는 단일 변환 — 아래 함수 주석 참고).
    and clock_timestamp() > ((c.submission_deadline + 1)::timestamp at time zone 'Asia/Seoul')
  ) as is_overdue
from core.demand_submission s
join core.planning_cycle c on c.cycle_id = s.cycle_id
left join (
  select submission_id,
         count(*) as total_line_count,
         count(*) filter (where jsonb_array_length(issues) > 0) as error_line_count
    from core.demand_submission_line
   group by submission_id
) l on l.submission_id = s.submission_id;

