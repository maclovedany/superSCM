-- Task 7 · 부서별 월간 수요 제출과 마감 관리
--
-- 목적: 1순위 병목인 부서별 수요 자료 취합 시간을 줄이고, 제출·회수·수정·합의 이력을 남긴다
-- (stage1.md §1 목표 우선순위, §3 "부서별 수요 자료 제출").
--
-- ★ 여기서 만든 제출 자료 자체는 조달 수요로 집계하지 않는다 — Task 8이 만들 "확정" 소스만
--   최종 발주계획에 들어간다. 이 마이그레이션은 취합 과정(제출·회수·합의)만 다룬다.
-- ★ 품목코드 검증은 STEP 4(core.v_item_master, core.normalize_item_id)를 그대로 재사용한다.
--   새 정규화 규칙을 만들지 않는다.
-- ★ 알 수 없는 품목·null 수량·잘못된 날짜는 조용히 지우지 않는다. core.demand_submission_line에
--   행을 그대로 남기고 issues(오류 사유)를 붙인다.
-- ★ 실제 Supabase 적용은 사용자가 SQL Editor에서 수동으로 수행한다. 이 파일은 다시 실행해도 안전하다.


-- ══ 1. 수요 취합 주기 ═══════════════════════════════════════════

create table if not exists core.planning_cycle (
  cycle_id            uuid primary key default gen_random_uuid(),
  plan_month          date not null check (plan_month = date_trunc('month', plan_month)::date),
  submission_deadline date not null,
  status              text not null default 'OPEN' check (status in ('OPEN', 'CLOSED')),
  is_active           boolean not null default true,
  opened_by           uuid not null references auth.users(id) on delete restrict,
  opened_at           timestamptz not null default now(),
  closed_by           uuid references auth.users(id) on delete restrict,
  closed_at           timestamptz,
  constraint planning_cycle_close_check check (
    (status = 'OPEN' and is_active and closed_by is null and closed_at is null)
    or (status = 'CLOSED' and not is_active and closed_by is not null and closed_at is not null)
  )
);

-- 한 달에 "열린" 주기는 하나만 허용한다(컨트롤러 판정 3). 닫힌 뒤 같은 달을 다시 열 수 있도록
-- 활성 행에만 유니크 제약을 건다 — 이전 이력은 지우지 않는다.
create unique index if not exists planning_cycle_active_month_idx
  on core.planning_cycle (plan_month) where is_active;

comment on table core.planning_cycle is
  'Task 7 — SCM 품목담당자(PLAN_CONFIRM) 또는 ADMIN이 여는 월별 수요 취합 주기';


-- ══ 2. 부서 제출본과 라인 ═══════════════════════════════════════

create table if not exists core.demand_submission (
  submission_id     uuid primary key default gen_random_uuid(),
  cycle_id          uuid not null references core.planning_cycle(cycle_id) on delete restrict,
  plan_month        date not null,
  department        text not null check (department in ('SCM', 'SALES', 'MARKETING', 'SERVICE', 'BIZ_DEV')),
  status            text not null default 'DRAFT' check (status in ('DRAFT', 'SUBMITTED', 'WITHDRAWN', 'AGREED')),
  created_by        uuid not null references auth.users(id) on delete restrict,
  submitted_by      uuid references auth.users(id) on delete restrict,
  submitted_at      timestamptz,
  withdrawn_by      uuid references auth.users(id) on delete restrict,
  withdrawn_at      timestamptz,
  withdraw_reason   text,
  agreed_by         uuid references auth.users(id) on delete restrict,
  agreed_at         timestamptz,
  last_modified_by  uuid not null references auth.users(id) on delete restrict,
  last_modified_at  timestamptz not null default now(),
  version           integer not null default 1 check (version > 0),
  created_at        timestamptz not null default now(),
  -- 동일 부서·기준월(취합 주기)의 활성 제출본은 하나뿐이다 — 검증 체크리스트 1번.
  unique (cycle_id, department)
);

create index if not exists demand_submission_department_idx
  on core.demand_submission (department, plan_month desc);

create table if not exists core.demand_submission_line (
  line_id        uuid primary key default gen_random_uuid(),
  submission_id  uuid not null references core.demand_submission(submission_id) on delete cascade,
  line_no        integer not null check (line_no > 0),
  raw_item_code  text,                 -- 원본 품목코드(입력 그대로)
  item_id        text,                 -- 표준 품목코드(core.normalize_item_id) — 매칭 실패 시 null
  qty            numeric,              -- 수량 — 없거나 숫자가 아니면 null(0으로 채우지 않는다)
  need_month     date,                 -- 필요월(월의 1일로 저장) — 형식이 아니면 null
  issues         jsonb not null default '[]'::jsonb check (jsonb_typeof(issues) = 'array'),
  created_at     timestamptz not null default now(),
  unique (submission_id, line_no)
);

create index if not exists demand_submission_line_submission_idx
  on core.demand_submission_line (submission_id, line_no);

comment on table core.demand_submission_line is
  'Task 7 — 부서 제출 한 줄. 품목코드 불일치·null 수량·잘못된 날짜도 행을 지우지 않고 issues로 남긴다';

create table if not exists core.demand_submission_event (
