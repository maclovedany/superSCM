-- Task 15 · 실습용(practice) 데이터 표식과 제거 절차
--
-- 목적: 수업에서 전체 업무 흐름을 눌러 볼 수 있도록 넣는 실습용 데이터가
--   (1) 어떤 행이 실습용인지 **한 곳에서** 식별되고,
--   (2) 그 데이터에서 나온 숫자를 보는 화면이 "이 숫자는 실습용 데이터 기반입니다"를 말할 수 있고,
--   (3) 문서화된 한 번의 명령으로 **실데이터를 건드리지 않고** 지워지도록 한다.
--
-- ★ 이 파일은 표식·조회·제거 **장치만** 만든다. 실습 데이터 자체는 넣지 않는다.
--   실제 실습 데이터는 `supabase/practice-data/*.sql`에 있고, 그 스크립트가 여기 함수를 부른다.
--   마이그레이션에 실습 데이터를 넣으면 실제 운영 배포가 스키마를 적용하는 것만으로 더미 행을
--   함께 설치하게 된다 — 그래서 의도적으로 분리한다.
--
-- 여기서 만드는 것
--   core.practice_dataset          실습 데이터 묶음 하나(라벨 · 활성 여부 · 복구 정보)
--   core.practice_object           그 묶음이 만든 모든 객체의 등기부(종류 · 키) — append 방식
--   core.open_practice_dataset()   ADMIN — 묶음을 연다
--   core.register_practice_object()ADMIN — 만든 객체를 등기한다
--   core.is_practice_item/batch/forecast_run/plan()   화면·뷰가 쓰는 판정 함수
--   core.remove_practice_dataset() ADMIN — 문서화된 제거 절차(지울 수 없는 것은 사유와 함께 보고)
--   analytics.v_practice_dataset · v_practice_object · v_practice_data_status
--   analytics.v_practice_item · v_practice_plan   화면이 행 단위로 실습 여부를 가릴 때 쓰는 목록
--
-- ★ 왜 기존 뷰에 is_practice 열을 덧붙이지 않았는가 — `create or replace view`는 열을 뺄 수 없다
--   (error.md #16 · #24). analytics.v_available_stock(0500) · v_inventory_performance(001150) ·
--   v_procurement_plan(000900)에 열을 덧붙이면, 이 저장소의 표준 복구 절차인 "전체를 파일명 순서로
--   다시 적용"의 두 번째 회차에서 그 앞 파일들이 좁은 정의를 다시 만들다가 멈춘다. 그래서 실습
--   표식은 **새 객체로만** 두고, 화면은 별도 조회 한 번으로 배너를 띄운다.
--
-- ★ 권한을 넓히지 않는다. 등기부는 읽기만 authenticated에 열고(숫자의 출처를 모든 사용자가 알아야
--   한다), 쓰기·제거는 core.is_admin()을 함수 본문에서 다시 확인한다. 실습 데이터 자체는 실데이터와
--   똑같은 RLS를 그대로 받는다 — 이 파일은 어떤 정책도 완화하지 않는다.
--
-- 다시 실행해도 안전합니다. 실제 Supabase 적용은 사용자가 SQL Editor에서 수동으로 수행합니다.


