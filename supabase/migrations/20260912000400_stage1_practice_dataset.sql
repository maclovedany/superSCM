create table if not exists core.practice_dataset (
  dataset_id      uuid primary key default gen_random_uuid(),
  label           text not null unique check (btrim(label) <> ''),
  note            text,
  active          boolean not null default true,
  -- 실습 묶음이 기존 운영 설정을 잠시 밀어낸 경우 되돌릴 값을 담는다(예: 이전 활성 forecast_setting).
  restore_payload jsonb not null default '{}'::jsonb check (jsonb_typeof(restore_payload) = 'object'),
  created_by      uuid references auth.users(id) on delete set null,
  created_at      timestamptz not null default now(),
  removed_by      uuid references auth.users(id) on delete set null,
  removed_at      timestamptz,
  constraint practice_dataset_removed_check check (
    (active and removed_at is null) or (not active and removed_at is not null)
  )
);

comment on table core.practice_dataset is
  'Task 15 — 실습용 데이터 묶음. label 하나가 "이번 수업용으로 넣은 것 전부"를 가리킨다. '
  '제거하면 active=false가 되고 행 자체는 이력으로 남는다(무엇을 언제 지웠는지가 사라지면 안 된다)';

create table if not exists core.practice_object (
  object_id     bigint generated by default as identity primary key,
  dataset_id    uuid not null references core.practice_dataset(dataset_id) on delete cascade,
  object_kind   text not null check (object_kind in (
                  'ITEM', 'SUPPLY_ENTITY', 'SUPPLIER', 'SUPPLIER_DEPARTURE',
                  'BUSINESS_CALENDAR', 'CALENDAR_READINESS',
                  'ITEM_POLICY', 'ITEM_POLICY_REVISION',
                  'UPLOAD_BATCH', 'FORECAST_SETTING', 'FORECAST_RUN', 'BACKTEST_RUN',
                  'PLANNING_CYCLE', 'DEMAND_SUBMISSION', 'PROCUREMENT_PLAN'
                )),
  object_key    text not null check (btrim(object_key) <> ''),
  note          text,
  registered_at timestamptz not null default now(),
  -- 한 객체는 한 묶음에만 속한다. 같은 품목코드를 두 실습 묶음이 동시에 소유할 수 없다.
  unique (object_kind, object_key)
);

create index if not exists practice_object_dataset_idx on core.practice_object (dataset_id, object_kind);

