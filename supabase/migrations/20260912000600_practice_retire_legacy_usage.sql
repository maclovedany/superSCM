-- Task 15 fix round 2 · 5회차 더미 사용 이력 정리(되돌릴 수 있게) + 제거 표식 보강
--
-- 여기서 만드는 것
--   core.retired_usage_history                    정리한 raw.usage_history 행의 보관소(원본 그대로)
--   core.retire_unverified_usage_history(...)     ADMIN — 출처 없는 사용 이력을 보관소로 옮긴다
--   core.restore_retired_usage_history(...)       보관소의 행을 raw.usage_history로 되돌린다
--   analytics.v_practice_retired_usage            보관 현황(행 수 · 기간)
--   core.remove_practice_dataset(...) 재정의       ★ 아래 두 가지를 더한다
--
-- ══ 1. 왜 정리하는가 ═══════════════════════════════════════════════
--
-- 배포 DB의 raw.usage_history에는 5회차 실습 더미 7,038행이 batch_id = null로 남아 있습니다.
-- Task 9b의 원천 게이트는 학습·검증 기간에 출처 없는 행이 한 줄이라도 걸치면 (정상적으로) 발주량
-- 계산을 막습니다. 그래서 실습 데이터의 학습 기간을 그 더미 **뒤로** 밀어야 했고, 그 결과 실습
-- 기준월이 실제 달력보다 미래가 되는 부작용이 있었습니다.
--
-- 출처 없는 행을 보관소로 옮기면 그 제약이 사라져 학습 기간이 실제 달력 월에 놓입니다.
--
-- ★ 지우지 않습니다. 원본 행을 jsonb로 그대로 보관하고, 실습 묶음을 제거할 때 자동으로 되돌립니다.
--   제가 만들지 않은 기존 데이터이므로 복구 불가능한 방식은 쓰지 않습니다.
-- ★ 대상은 **출처가 없는 행만**입니다. 판정 조건은 원천 게이트가 보는 것과 정확히 같습니다
--   (batch_id가 없거나 · 그 배치가 IMPORTED usage_history가 아니거나 · source_type이 FILE_UPLOAD가 아님).
--   출처가 있는 행은 한 줄도 건드리지 않습니다.
--
-- ══ 2. N1 — 남는 행의 실습 표식이 벗겨지던 것 ═══════════════════════
--
-- 이전 정의는 발주계획이 있으면 FORECAST_RUN만 blocked에 넣고 v_backtests를 비웠습니다. 그래서
-- backtest_run · model_performance · champion_model_selection 행은 **남는데** BACKTEST_RUN 등기는
-- 지워졌습니다. item_policy_revision도 같은 문제였습니다(행은 남고 등기만 삭제).
-- 결과적으로 그 행들이 화면에서 더 이상 실습용으로 식별되지 않았습니다 — 표식이 무너지는 것이라
-- 이 작업의 근본 취지에 정면으로 어긋납니다.
--
-- 이번 정의는 두 가지를 바꿉니다.
--   (a) 계획 때문에 남는 Backtest 실행도 blocked에 넣습니다.
--   (b) 등기 정리를 "종류별 예외 목록"이 아니라 **그 객체가 실제로 지워졌는가**로 판정합니다.
--       살아남은 행의 등기는 종류와 무관하게 남습니다 — 같은 부류의 버그가 다시 생기지 않습니다.
--
-- ★ core.remove_practice_dataset은 20260912000400과 이 파일 두 곳에 있습니다. 파일명 순서상
--   **이 파일이 최종본**입니다. 0400의 본문을 고칠 때는 반드시 여기도 같이 고쳐야 합니다
--   (core.commit_import_batch가 STEP 4 · 0500 · 1150 세 곳에 있는 것과 같은 관례입니다).
--
-- 다시 실행해도 안전합니다. 실제 Supabase 적용은 사용자가 SQL Editor에서 수동으로 수행합니다.


-- ══ 3. 보관소 ══════════════════════════════════════════════════════

create table if not exists core.retired_usage_history (
  archive_id  bigint generated by default as identity primary key,
  dataset_id  uuid not null references core.practice_dataset(dataset_id) on delete restrict,
  -- 원본 행 전체를 그대로 보관한다. 컬럼이 늘어나도 복구가 깨지지 않는다.
  row_data    jsonb not null check (jsonb_typeof(row_data) = 'object'),
  use_date    date,
  retired_by  uuid references auth.users(id) on delete set null,
  retired_at  timestamptz not null default now()
);

create index if not exists retired_usage_history_dataset_idx on core.retired_usage_history (dataset_id);

comment on table core.retired_usage_history is
  'Task 15 fix round 2 — 출처 없는 raw.usage_history 행의 보관소. 지우지 않고 옮겨 둔다. '
  '실습 묶음을 제거하면 core.remove_practice_dataset이 자동으로 되돌린다';
comment on column core.retired_usage_history.row_data is
  '원본 raw.usage_history 행 전체(to_jsonb). 복구는 jsonb_populate_record로 원래 모양 그대로 되돌린다';


-- ══ 4. 정리 · 복구 함수 ════════════════════════════════════════════

create or replace function core.retire_unverified_usage_history(p_label text, p_confirm boolean default false)
returns jsonb
language plpgsql security definer set search_path = core, raw, public, pg_temp
as $$
declare
  v_dataset core.practice_dataset%rowtype;
  v_moved bigint;
  v_deleted bigint;
  v_min date;
  v_max date;
begin
  if not core.is_admin() then
    raise exception '관리자 권한이 필요합니다.' using errcode = '42501';
  end if;
  if not coalesce(p_confirm, false) then
    raise exception '정리를 실행하려면 p_confirm => true 를 명시해야 합니다.' using errcode = '22023';
  end if;

  select * into v_dataset from core.practice_dataset where label = btrim(p_label) and active for update;
  if not found then
    raise exception '열려 있는 실습 데이터 묶음을 찾을 수 없습니다: %', p_label using errcode = 'P0002';
  end if;

  -- ★ 판정 조건은 core.procurement_forecast_source_status가 보는 것과 정확히 같다.
  --   "검증됨" = 그 batch_id의 배치가 실재하고 · IMPORTED이고 · usage_history이고 · source_type이
  --   FILE_UPLOAD인 것. 그 밖이 전부 "출처 없음"이다.
  --
  -- ★★ 보관과 삭제는 **글자 그대로 같은 술어**를 써야 한다. 다른 술어를 쓰면
  --   (예: 보관은 left join의 b.batch_id is null, 삭제는 배치가 실재해야 하는 조건)
  --   batch_id가 존재하지 않는 배치를 가리키는 행이 보관만 되고 삭제되지 않아, 복구할 때
  --   **중복 행**이 된다. 아래 건수 비교가 그 경우를 소리 내어 막는다.
  -- ★ source_type이 null일 때 3값 논리로 조건이 null이 되지 않도록 is not distinct from을 쓴다.
  insert into core.retired_usage_history (dataset_id, row_data, use_date, retired_by)
  select v_dataset.dataset_id, to_jsonb(u), u.use_date, auth.uid()
    from raw.usage_history u
   where not (
     exists (select 1 from core.upload_batch b
              where b.batch_id = u.batch_id and b.status = 'IMPORTED' and b.import_type = 'usage_history')
     and u.source_type is not distinct from 'FILE_UPLOAD'
   );
  get diagnostics v_moved = row_count;

  delete from raw.usage_history u
   where not (
     exists (select 1 from core.upload_batch b
              where b.batch_id = u.batch_id and b.status = 'IMPORTED' and b.import_type = 'usage_history')
     and u.source_type is not distinct from 'FILE_UPLOAD'
   );
  get diagnostics v_deleted = row_count;

  if v_deleted is distinct from v_moved then
    raise exception '보관 건수(%)와 삭제 건수(%)가 다릅니다 — 복구 시 중복이 생기므로 정리를 중단합니다.',
      v_moved, v_deleted using errcode = '22023';
  end if;

  select min(use_date), max(use_date) into v_min, v_max
    from core.retired_usage_history where dataset_id = v_dataset.dataset_id;

  insert into core.audit_log (actor, action, target_type, target_id, before, after)
  values (auth.uid(), 'LEGACY_USAGE_RETIRED', 'retired_usage_history', v_dataset.dataset_id::text, null,
          jsonb_build_object('label', v_dataset.label, 'rows', v_moved, 'min_use_date', v_min, 'max_use_date', v_max));

  return jsonb_build_object(
    'label', v_dataset.label, 'retired_rows', v_moved,
    'min_use_date', v_min, 'max_use_date', v_max,
    'remaining_unverified_rows', (
      select count(*) from raw.usage_history u
       left join core.upload_batch b on b.batch_id = u.batch_id
      where b.batch_id is null or b.status <> 'IMPORTED' or b.import_type <> 'usage_history'
         or u.source_type is distinct from 'FILE_UPLOAD')
  );
end;
$$;

comment on function core.retire_unverified_usage_history(text, boolean) is
  'Task 15 fix round 2 — ADMIN. 출처 없는 raw.usage_history 행을 core.retired_usage_history로 옮긴다. '
  '지우지 않으며, 실습 묶음 제거 시 자동으로 되돌아온다. p_confirm => true 필수';

create or replace function core.restore_retired_usage_history(p_dataset_id uuid)
returns bigint
language plpgsql security definer set search_path = core, raw, public, pg_temp
as $$
declare
  v_restored bigint := 0;
  v_row record;
begin
  for v_row in
    select archive_id, row_data from core.retired_usage_history where dataset_id = p_dataset_id order by archive_id
  loop
    insert into raw.usage_history
    select * from jsonb_populate_record(null::raw.usage_history, v_row.row_data);
    v_restored := v_restored + 1;
  end loop;

  delete from core.retired_usage_history where dataset_id = p_dataset_id;
  return v_restored;
end;
$$;

comment on function core.restore_retired_usage_history(uuid) is
  'Task 15 fix round 2 — 보관소의 행을 raw.usage_history로 되돌리고 보관소를 비운다. '
  'core.remove_practice_dataset이 부른다(권한 검사는 호출자가 한다)';

revoke all on function core.restore_retired_usage_history(uuid) from public, anon, authenticated;
revoke all on function core.retire_unverified_usage_history(text, boolean) from public, anon;
grant execute on function core.retire_unverified_usage_history(text, boolean) to authenticated;


