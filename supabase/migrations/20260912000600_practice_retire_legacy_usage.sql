-- ★ fix round 3 — security_invoker를 반드시 붙인다. 아래에서 core.retired_usage_history에 RLS를
--   켜고 core.is_admin()으로 제한해 놓고도, 뷰가 소유자 권한으로 돌면 일반 사용자가 이 뷰를 통해
--   보관 건수·기간을 그대로 읽는다(원본 테이블은 0행인데 뷰는 1행이 보이는 상태). 이 저장소의
--   다른 운영 뷰와 같은 관례다(SCHEMA.md — 신규 analytics 운영 뷰는 security_invoker = true).
create or replace view analytics.v_practice_retired_usage
with (security_invoker = true)
as
select d.label,
       d.active,
       count(r.archive_id)   as retired_rows,
       min(r.use_date)       as min_use_date,
       max(r.use_date)       as max_use_date,
       min(r.retired_at)     as retired_at
  from core.practice_dataset d
  join core.retired_usage_history r on r.dataset_id = d.dataset_id
 group by d.label, d.active;

comment on view analytics.v_practice_retired_usage is
  'Task 15 fix round 2 — 정리해 보관 중인 5회차 더미 사용 이력 현황. 실습 묶음을 제거하면 되돌아온다';

