-- ══ 6. core.remove_practice_dataset 재정의 ═════════════════════════
--
-- ★ 20260912000400의 정의를 그대로 두고 두 가지만 바꾼다(N1 + 보관 행 복구).
--   0400을 고칠 때는 여기도 반드시 같이 고친다 — 파일명 순서상 이쪽이 최종본이다.

create or replace function core.remove_practice_dataset(p_label text, p_confirm boolean default false)
returns jsonb
language plpgsql security definer set search_path = core, public, pg_temp
as $$
declare
  v_dataset   core.practice_dataset%rowtype;
  v_blocked   jsonb := '[]'::jsonb;
  v_removed   jsonb := '{}'::jsonb;
  v_items     text[];
  v_blocked_items text[] := '{}';
  v_batches   uuid[];
  v_runs      uuid[];
  v_backtests uuid[];
  v_plans     uuid[];
  v_n         bigint;
  v_total     bigint := 0;
  v_key       text;
begin
  if not core.is_admin() then
    raise exception '관리자 권한이 필요합니다.' using errcode = '42501';
  end if;
  if not coalesce(p_confirm, false) then
    raise exception '제거를 실행하려면 p_confirm => true 를 명시해야 합니다.' using errcode = '22023';
  end if;

  select * into v_dataset from core.practice_dataset where label = btrim(p_label) for update;
  if not found then
    raise exception '실습 데이터 묶음을 찾을 수 없습니다: %', p_label using errcode = 'P0002';
  end if;
  if not v_dataset.active then
    raise exception '이미 제거된 실습 데이터 묶음입니다: %', p_label using errcode = '22023';
  end if;

  select coalesce(array_agg(object_key), '{}') into v_items
    from core.practice_object where dataset_id = v_dataset.dataset_id and object_kind = 'ITEM';
  select coalesce(array_agg(object_key::uuid), '{}') into v_batches
    from core.practice_object where dataset_id = v_dataset.dataset_id and object_kind = 'UPLOAD_BATCH';
  select coalesce(array_agg(object_key::uuid), '{}') into v_runs
    from core.practice_object where dataset_id = v_dataset.dataset_id and object_kind = 'FORECAST_RUN';
  select coalesce(array_agg(object_key::uuid), '{}') into v_backtests
    from core.practice_object where dataset_id = v_dataset.dataset_id and object_kind = 'BACKTEST_RUN';
  select coalesce(array_agg(object_key::uuid), '{}') into v_plans
    from core.practice_object where dataset_id = v_dataset.dataset_id and object_kind = 'PROCUREMENT_PLAN';

  -- ── 사람이 이미 업무를 한 품목은 지우지 않는다 ───────────────────
  for v_key in
    select distinct acted.item_id
      from (
        select l.item_id from core.sales_order_line l
        union all select a.item_id from core.stock_allocation a
        union all select u.item_id from core.urgent_order u
        union all select m.item_id from core.supply_meeting_result m
        union all select e.item_id from core.event_demand e
      ) acted
     where acted.item_id = any(v_items)
  loop
    v_blocked := v_blocked || jsonb_build_array(jsonb_build_object(
      'kind', 'ITEM', 'key', v_key, 'reason', 'ACTED_ON_BY_USER'));
    v_items := array_remove(v_items, v_key);
    v_blocked_items := array_append(v_blocked_items, v_key);
  end loop;

  -- 발주계획 라인이 참조하는 품목도 지우지 않는다(계획은 어떤 상태에서도 삭제할 수 없다).
  for v_key in
    select distinct l.item_id from core.procurement_plan_line l where l.item_id = any(v_items)
  loop
    v_blocked := v_blocked || jsonb_build_array(jsonb_build_object(
      'kind', 'ITEM', 'key', v_key, 'reason', 'PLAN_REFERENCES_ITEM'));
    v_items := array_remove(v_items, v_key);
    v_blocked_items := array_append(v_blocked_items, v_key);
  end loop;

  if to_regclass('core.receipt_schedule_result') is not null then
    for v_key in
      select distinct s.supplier_id
        from core.procurement_schedule s
        join core.receipt_schedule_result r on r.schedule_id = s.schedule_id
       where r.actual_receipt_date is not null and s.supplier_id is not null
         and exists (select 1 from core.practice_object o
                      where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'SUPPLIER' and o.object_key = s.supplier_id)
    loop
      v_blocked := v_blocked || jsonb_build_array(jsonb_build_object(
        'kind', 'SUPPLIER', 'key', v_key, 'reason', 'SCHEDULE_ACTUAL_RECORDED'));
    end loop;
  end if;

  for v_key in select p::text from unnest(v_plans) as p loop
    v_blocked := v_blocked || jsonb_build_array(jsonb_build_object(
      'kind', 'PROCUREMENT_PLAN', 'key', v_key, 'reason', 'PLAN_IMMUTABLE_HISTORY'));
  end loop;

  -- ── 지울 수 있는 것을 의존 순서대로 지운다 ───────────────────────
  if exists (select 1 from core.procurement_plan p where p.forecast_run_id = any(v_runs)) then
    for v_key in select r::text from unnest(v_runs) as r loop
      v_blocked := v_blocked || jsonb_build_array(jsonb_build_object(
        'kind', 'FORECAST_RUN', 'key', v_key, 'reason', 'PLAN_IMMUTABLE_HISTORY'));
    end loop;
    -- ★ fix round 2 (N1) — 그 실행을 참조하는 Backtest · Champion · 모델 성능 행도 함께 남는다.
    --   여기서 blocked에 넣지 않으면 행은 남는데 등기만 지워져, 그 행들이 화면에서 실습용으로
    --   식별되지 않는다(/admin/backtest-runs · champion-models 안내가 조용히 사라진다).
    for v_key in select b::text from unnest(v_backtests) as b loop
      v_blocked := v_blocked || jsonb_build_array(jsonb_build_object(
        'kind', 'BACKTEST_RUN', 'key', v_key, 'reason', 'PLAN_IMMUTABLE_HISTORY'));
    end loop;
    v_runs := '{}';
    v_backtests := '{}';
  end if;

  delete from core.champion_model_selection where backtest_run_id = any(v_backtests);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('champion_model_selection', v_n); v_total := v_total + v_n;
  delete from core.model_performance where backtest_run_id = any(v_backtests);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('model_performance', v_n); v_total := v_total + v_n;
  delete from core.backtest_run where backtest_run_id = any(v_backtests);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('backtest_run', v_n); v_total := v_total + v_n;

  delete from core.forecast_run where run_id = any(v_runs);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('forecast_run', v_n); v_total := v_total + v_n;

  delete from core.demand_submission_event e
   where e.submission_id in (select s.submission_id from core.demand_submission s
                              where s.cycle_id in (select o.object_key::uuid from core.practice_object o
                                                    where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'PLANNING_CYCLE'));
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('demand_submission_event', v_n); v_total := v_total + v_n;
  delete from core.demand_submission s
   where s.cycle_id in (select o.object_key::uuid from core.practice_object o
                         where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'PLANNING_CYCLE');
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('demand_submission', v_n); v_total := v_total + v_n;
  delete from core.planning_cycle c
   where c.cycle_id in (select o.object_key::uuid from core.practice_object o
                         where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'PLANNING_CYCLE');
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('planning_cycle', v_n); v_total := v_total + v_n;

  delete from core.month_end_inventory_snapshot where item_id = any(v_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('month_end_inventory_snapshot', v_n); v_total := v_total + v_n;
  delete from core.stock_receipt_ledger where item_id = any(v_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('stock_receipt_ledger', v_n); v_total := v_total + v_n;
  delete from core.stock_balance where item_id = any(v_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('stock_balance', v_n); v_total := v_total + v_n;

  delete from core.item_policy_revision where item_id = any(v_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('item_policy_revision', v_n); v_total := v_total + v_n;
  delete from core.item_policy where item_id = any(v_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('item_policy', v_n); v_total := v_total + v_n;

  delete from raw.usage_history
   where batch_id = any(v_batches)
     and upper(regexp_replace(coalesce(item_id, ''), '[\s\-_]', '', 'g')) <> all(v_blocked_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('raw.usage_history', v_n); v_total := v_total + v_n;
  delete from raw.inventory
   where batch_id = any(v_batches)
     and upper(regexp_replace(coalesce("품목코드", ''), '[\s\-_]', '', 'g')) <> all(v_blocked_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('raw.inventory', v_n); v_total := v_total + v_n;
  delete from raw.item_master
   where batch_id = any(v_batches)
     and upper(regexp_replace(coalesce("품목코드", ''), '[\s\-_]', '', 'g')) <> all(v_blocked_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('raw.item_master', v_n); v_total := v_total + v_n;
  delete from raw.goods_receipt
   where batch_id = any(v_batches)
     and upper(regexp_replace(coalesce("품목코드", ''), '[\s\-_]', '', 'g')) <> all(v_blocked_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('raw.goods_receipt', v_n); v_total := v_total + v_n;
  delete from raw.purchase_order
   where batch_id = any(v_batches)
     and upper(regexp_replace(coalesce("품목코드", ''), '[\s\-_]', '', 'g')) <> all(v_blocked_items);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('raw.purchase_order', v_n); v_total := v_total + v_n;
  delete from raw.supplier_master where batch_id = any(v_batches);
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('raw.supplier_master', v_n); v_total := v_total + v_n;

  if array_length(v_blocked_items, 1) is null then
    delete from core.upload_batch where batch_id = any(v_batches);
    get diagnostics v_n = row_count;
  else
    v_n := 0;
    for v_key in select b::text from unnest(v_batches) as b loop
      v_blocked := v_blocked || jsonb_build_array(jsonb_build_object(
        'kind', 'UPLOAD_BATCH', 'key', v_key, 'reason', 'RETAINED_FOR_BLOCKED_ITEM'));
    end loop;
  end if;
  v_removed := v_removed || jsonb_build_object('upload_batch', v_n); v_total := v_total + v_n;

  delete from core.supplier_departure d
   where d.departure_id in (select o.object_key::bigint from core.practice_object o
                             where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'SUPPLIER_DEPARTURE');
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('supplier_departure', v_n); v_total := v_total + v_n;

  v_n := 0;
  for v_key in
    select o.object_key from core.practice_object o
     where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'SUPPLIER'
       and not exists (select 1 from jsonb_array_elements(v_blocked) b
                        where b->>'kind' = 'SUPPLIER' and b->>'key' = o.object_key)
  loop
    begin
      delete from core.supplier where supplier_id = v_key;
      v_n := v_n + 1;
    exception when foreign_key_violation then
      v_blocked := v_blocked || jsonb_build_array(jsonb_build_object(
        'kind', 'SUPPLIER', 'key', v_key, 'reason', 'FK_IN_USE'));
    end;
  end loop;
  v_removed := v_removed || jsonb_build_object('supplier', v_n); v_total := v_total + v_n;

  delete from core.business_calendar c
   where (c.country_code || ':' || c.calendar_date::text) in (
     select o.object_key from core.practice_object o
      where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'BUSINESS_CALENDAR');
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('business_calendar', v_n); v_total := v_total + v_n;

  delete from core.business_calendar_readiness r
   where (r.country_code || ':' || r.cal_year::text || '-' || lpad(r.cal_month::text, 2, '0')) in (
     select o.object_key from core.practice_object o
      where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'CALENDAR_READINESS');
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('business_calendar_readiness', v_n); v_total := v_total + v_n;

  update core.supply_entity e
     set prep_days = coalesce((v_dataset.restore_payload -> 'supply_entity_prep_days' ->> e.entity_id)::integer, e.prep_days),
         updated_at = now()
   where e.entity_id in (select o.object_key from core.practice_object o
                          where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'SUPPLY_ENTITY');
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('supply_entity_restored', v_n);

  delete from core.forecast_setting s
   where s.setting_id in (select o.object_key::uuid from core.practice_object o
                           where o.dataset_id = v_dataset.dataset_id and o.object_kind = 'FORECAST_SETTING');
  get diagnostics v_n = row_count; v_removed := v_removed || jsonb_build_object('forecast_setting', v_n); v_total := v_total + v_n;
  if v_dataset.restore_payload ? 'previous_forecast_setting_id' then
    update core.forecast_setting
       set active = true, updated_at = now()
     where setting_id = (v_dataset.restore_payload ->> 'previous_forecast_setting_id')::uuid;
  end if;

  -- ★ fix round 2 — 정리해 둔 5회차 더미 사용 이력을 되돌린다. 제가 만들지 않은 기존 데이터이므로
  --   실습을 걷어내면 원래 자리로 돌아가야 한다.
  v_n := core.restore_retired_usage_history(v_dataset.dataset_id);
  v_removed := v_removed || jsonb_build_object('raw.usage_history_restored', v_n);

  -- ── 등기 정리 ────────────────────────────────────────────────────
  -- ★ fix round 2 (N1) — "지워졌는가"로 판정한다. 살아남은 행의 등기는 종류와 무관하게 남긴다.
  --   이전 정의는 종류별 예외 목록이라 BACKTEST_RUN · ITEM_POLICY_REVISION처럼 목록에 없는 종류의
  --   등기가 행이 남았는데도 지워졌다(표식이 벗겨졌다).
  -- ★ fix round 3 — 아래 case가 모르는 종류(나중에 추가될 object_kind)는 **남긴다**. 남겼다는
  --   사실을 결과에 함께 보고해 조용히 넘어가지 않게 한다. 모르는 것을 지우는 쪽으로 기본값을
  --   두면, 종류가 늘어날 때마다 N1과 똑같은 방식으로 표식이 벗겨진다.
  -- ★★ Task 17 리뷰 fix round 1(2026-09-12) — ITEM 존재 검사를 core.v_item_master(화면
  --   가시성, 출처 게이트가 걸린 뷰)가 아니라 raw.item_master(원본 행 존재)로 바꾼다. 이
  --   블록의 질문은 "이 등기가 가리키는 원본 행이 아직 있는가"이지 "지금 화면에 보이는가"가
  --   아니다 — 화면 가시성과 등기 유효성은 다른 축이다(리뷰어 실측: 출처 없는 품목을 ITEM으로
  --   등기하면 게이트 뒤 core.v_item_master에서 사라져 이 DELETE가 "원본이 없어졌다"고 오판해
  --   실습 표식을 지웠다 — N1과 같은 실패 모드, 이번엔 게이트가 새로 만든 구멍이다). 배포
  --   DB의 실습 11품목이 전부 batch_id를 갖는 것은 지금 데이터의 우연일 뿐
  --   core.register_practice_object가 강제하는 불변식이 아니다(그 함수는 core.practice_object
  --   에만 INSERT하고 raw.item_master.batch_id를 전혀 건드리지 않는다) — 그러니 이 존재
  --   검사도 그 우연에 기대면 안 된다.
  select v_blocked || coalesce(jsonb_agg(jsonb_build_object(
           'kind', o.object_kind, 'key', o.object_key, 'reason', 'UNKNOWN_OBJECT_KIND')), '[]'::jsonb)
    into v_blocked
    from core.practice_object o
   where o.dataset_id = v_dataset.dataset_id
     and o.object_kind not in (
       'ITEM', 'ITEM_POLICY', 'ITEM_POLICY_REVISION', 'UPLOAD_BATCH', 'FORECAST_RUN', 'BACKTEST_RUN',
       'PROCUREMENT_PLAN', 'PLANNING_CYCLE', 'DEMAND_SUBMISSION', 'SUPPLIER', 'SUPPLIER_DEPARTURE',
       'BUSINESS_CALENDAR', 'CALENDAR_READINESS', 'FORECAST_SETTING', 'SUPPLY_ENTITY'
     );

  delete from core.practice_object o
   where o.dataset_id = v_dataset.dataset_id
     and not case o.object_kind
       when 'ITEM'                 then exists (select 1 from raw.item_master m where core.normalize_item_id(m."품목코드") = o.object_key)
       when 'ITEM_POLICY'          then exists (select 1 from core.item_policy p where p.item_id = o.object_key)
       when 'ITEM_POLICY_REVISION' then exists (select 1 from core.item_policy_revision r where r.revision_id::text = o.object_key)
       when 'UPLOAD_BATCH'         then exists (select 1 from core.upload_batch b where b.batch_id::text = o.object_key)
       when 'FORECAST_RUN'         then exists (select 1 from core.forecast_run r where r.run_id::text = o.object_key)
       when 'BACKTEST_RUN'         then exists (select 1 from core.backtest_run b where b.backtest_run_id::text = o.object_key)
       when 'PROCUREMENT_PLAN'     then exists (select 1 from core.procurement_plan p where p.plan_id::text = o.object_key)
       when 'PLANNING_CYCLE'       then exists (select 1 from core.planning_cycle c where c.cycle_id::text = o.object_key)
       when 'DEMAND_SUBMISSION'    then exists (select 1 from core.demand_submission s where s.submission_id::text = o.object_key)
       when 'SUPPLIER'             then exists (select 1 from core.supplier s where s.supplier_id = o.object_key)
       when 'SUPPLIER_DEPARTURE'   then exists (select 1 from core.supplier_departure d where d.departure_id::text = o.object_key)
       when 'BUSINESS_CALENDAR'    then exists (select 1 from core.business_calendar c
                                                 where c.country_code || ':' || c.calendar_date::text = o.object_key)
       when 'CALENDAR_READINESS'   then exists (select 1 from core.business_calendar_readiness r
                                                 where r.country_code || ':' || r.cal_year::text || '-' || lpad(r.cal_month::text, 2, '0') = o.object_key)
       when 'FORECAST_SETTING'     then exists (select 1 from core.forecast_setting s where s.setting_id::text = o.object_key)
       -- 해외법인 행은 지우지 않고 준비기간만 원래 값으로 되돌리므로, 더 이상 실습 객체가 아니다.
       when 'SUPPLY_ENTITY'        then false
       -- ★ fix round 3 — 모르는 종류는 **남긴다**(위에서 UNKNOWN_OBJECT_KIND로 보고했다).
       --   이전 정의는 else false였고, 그래서 case에 없는 종류의 등기가 조용히 지워졌다.
       else true
     end;

  update core.practice_dataset
     set active = false, removed_by = auth.uid(), removed_at = clock_timestamp()
   where dataset_id = v_dataset.dataset_id;

  insert into core.audit_log (actor, action, target_type, target_id, before, after)
  values (auth.uid(), 'PRACTICE_DATASET_REMOVED', 'practice_dataset', v_dataset.dataset_id::text,
          jsonb_build_object('label', v_dataset.label),
          jsonb_build_object('removed', v_removed, 'blocked', v_blocked, 'total_rows_deleted', v_total));

  return jsonb_build_object(
    'label', v_dataset.label,
    'total_rows_deleted', v_total,
    'removed', v_removed,
    'blocked', v_blocked,
    'residual_objects', (select count(*) from core.practice_object where dataset_id = v_dataset.dataset_id)
  );
end;
$$;

